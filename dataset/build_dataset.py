def build() -> None:
    """写入 problems.jsonl 并打印统计信息."""
    root = Path(__file__).parent
    output = root / "problems.jsonl"

    with output.open("w", encoding="utf-8") as f:
        for p in PROBLEMS:
            f.write(json.dumps(p, ensure_ascii=False) + "\n")

    # 统计
    levels = {}
    for p in PROBLEMS:
        levels[p["level"]] = levels.get(p["level"], 0) + 1

    print(f"已生成题库: {output}")
    print(f"总题数: {len(PROBLEMS)}")
    for lv in sorted(levels):
        print(f"  {lv}: {levels[lv]} 题")


